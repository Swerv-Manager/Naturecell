# Dev-only: compose the Vidunder Olien "bottle + carton" packshot from two real product photos
# (dropper cut from startpakke-plus, carton from skin-oil-hires) -> skin-oil-duo.js (data URI module).
import base64, io, sys, os
from PIL import Image, ImageFilter, ImageChops
A = sys.argv[1]; OUT = sys.argv[2]
g = Image.open(f'{A}/products/startpakke-plus.webp').convert('RGBA')
b = g.crop((766, 400, 994, 1100))
al = b.getchannel('A').point(lambda v: 255 if v >= 250 else 0).filter(ImageFilter.MinFilter(3)).filter(ImageFilter.GaussianBlur(0.9))
b.putalpha(ImageChops.multiply(al, b.getchannel('A')))
b = b.crop(b.getchannel('A').point(lambda v: 255 if v > 40 else 0).getbbox())
box = Image.open(f'{A}/products/skin-oil-hires.webp').convert('RGBA')
box = box.crop(box.getchannel('A').point(lambda v: 255 if v > 200 else 0).getbbox())
S = 1000; floor = 960
BH = 860; box = box.resize((round(box.width * BH / box.height), BH), Image.LANCZOS)
DH = round(BH * 0.86); b = b.resize((round(b.width * DH / b.height), DH), Image.LANCZOS)
gap = 26; W = b.width + gap + box.width; x0 = (S - W) // 2
c = Image.new('RGBA', (S, S), (0, 0, 0, 0))
c.alpha_composite(box, (x0 + b.width + gap, floor - BH))
c.alpha_composite(b, (x0, floor - DH))
print('bbox', c.getchannel('A').point(lambda v: 255 if v > 200 else 0).getbbox(), c.size)
buf = io.BytesIO(); c.save(buf, 'WEBP', quality=84, method=6)
open(OUT, 'w').write('// Generated by .dev/duo.py – composite of two real NatureCell packshots (carton + dropper).\nexport default "data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode() + '";\n')
c.convert('RGBA').save(os.path.join(os.path.dirname(OUT), '.dev', 'skin-oil-duo.png'))
print(len(buf.getvalue()))
