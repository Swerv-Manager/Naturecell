# Dev-only: cut the individual bottles out of the two real NatureCell group packshots (same studio, same scale),
# drop the photographed floor/reflection (hard alpha + 1px feather) and emit them as data-URI WebPs -> set-bottles.js.
# The Sampakke cards stand these bottles in a line on the same floor as the single cards, so every bottle has
# the same px height everywhere on the page (truthful relative scale) and the set shows exactly what it contains.
import base64, io, sys, os, json
from PIL import Image, ImageFilter, ImageChops
A = sys.argv[1]; OUT = sys.argv[2]
SRC = {
  'cleansing-gel': ('all-day-facial.webp', (150, 60, 484, 1130)),
  'day-cream':     ('all-day-facial.webp', (490, 60, 746, 1130)),
  'night-cream':   ('all-day-facial.webp', (750, 60, 1000, 1130)),
  'skin-oil':      ('startpakke-plus.webp', (760, 380, 1000, 1130)),
}
H = 760  # px height of the tallest cut (day cream) – plenty for 2x DPR at card size
res = {}
for k, (f, box) in SRC.items():
  g = Image.open(f'{A}/products/{f}').convert('RGBA').crop(box)
  a = g.getchannel('A')
  hard = a.point(lambda v: 255 if v >= 246 else 0).filter(ImageFilter.MinFilter(3)).filter(ImageFilter.GaussianBlur(0.8))
  g.putalpha(ImageChops.multiply(hard, a))
  bb = g.getchannel('A').point(lambda v: 255 if v > 24 else 0).getbbox()
  g = g.crop(bb)
  res[k] = g
scale = H / res['day-cream'].height
out = {}
for k, g in res.items():
  g = g.resize((round(g.width * scale), round(g.height * scale)), Image.LANCZOS)
  buf = io.BytesIO(); g.save(buf, 'WEBP', quality=86, method=6)
  out[k] = {'url': 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode(), 'w': g.width, 'h': g.height}
  g.save(os.path.join(os.path.dirname(OUT), '.dev', f'set-{k}.png'))
  print(k, g.size, len(buf.getvalue()))
open(OUT, 'w').write('// Generated by .dev/sets.py – single bottles cut from the real NatureCell group packshots (all-day-facial + startpakke-plus).\nexport default ' + json.dumps(out) + ';\n')
